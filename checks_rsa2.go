package badkeys

import (
	"math/big"
	"sync"
)

const maxSmallPrime = 65537

var (
	smallPrimeProdOnce sync.Once
	smallPrimeProd     *big.Int
)

// smallPrimesProduct returns the product of all primes p with 2 <= p <= 65537.
func smallPrimesProduct() *big.Int {
	smallPrimeProdOnce.Do(func() {
		sieve := make([]bool, maxSmallPrime+1)
		prod := big.NewInt(1)
		for i := 2; i <= maxSmallPrime; i++ {
			if sieve[i] {
				continue
			}
			prod.Mul(prod, big.NewInt(int64(i)))
			for j := i * 2; j <= maxSmallPrime; j += i {
				sieve[j] = true
			}
		}
		smallPrimeProd = prod
	})
	return smallPrimeProd
}

// smallfactors detects RSA moduli with a small prime factor (<= 65537), which
// almost always means a corrupt key.
func smallfactors(n, e *big.Int) *Finding {
	if n.Cmp(big.NewInt(5)) <= 0 {
		return nil
	}
	factor := new(big.Int).GCD(nil, nil, smallPrimesProduct(), n)
	if factor.Cmp(big1) == 0 {
		return nil
	}
	p := factor
	q := new(big.Int).Div(n, factor)
	sub := "valid"
	if !isProbablePrime(p) || !isProbablePrime(q) {
		sub = "corrupt"
	}
	return &Finding{P: p, Q: q, Subtest: sub}
}

// hasSmallFactor is a lightweight helper used by rsabias/rsapoly: it mirrors
// the Python "if smallfactors(n)" truthiness test.
func hasSmallFactor(n *big.Int) bool {
	return smallfactors(n, nil) != nil
}

// roca detects RSA keys generated by the vulnerable Infineon library (the
// "Return of the Coppersmith Attack" / CVE-2017-15361).
func roca(n, e *big.Int) *Finding {
	generator := big.NewInt(65537)
	generatorOrder := big.NewInt(2454106387091158800)
	pp := []int64{16, 81, 25, 7, 11, 13, 17, 23, 29, 37, 41, 53, 83}
	modulus, _ := new(big.Int).SetString("924CBA6AE99DFA084537FACC54948DF0C23DA044D8CABE0EDD75BC6", 16)

	if n.Cmp(big2) <= 0 {
		return nil
	}
	if new(big.Int).Exp(n, generatorOrder, modulus).Cmp(big1) != 0 {
		return nil
	}

	for _, primePower := range pp {
		orderDivPP := new(big.Int).Div(generatorOrder, big.NewInt(primePower))
		gDash := new(big.Int).Exp(generator, orderDivPP, modulus)
		hDash := new(big.Int).Exp(n, orderDivPP, modulus)
		found := false
		acc := big.NewInt(1)
		for i := int64(0); i < primePower; i++ {
			if acc.Cmp(hDash) == 0 {
				found = true
				break
			}
			acc.Mul(acc, gDash)
			acc.Mod(acc, modulus)
		}
		if !found {
			return nil
		}
	}
	return &Finding{}
}

// rsawarnings flags RSA keys with weak sizes or unusual exponents.
func rsawarnings(n, e *big.Int) *Finding {
	bits := n.BitLen()
	switch {
	case bits < 768:
		return &Finding{Subtest: "extremely_small"}
	case bits < 2048:
		return &Finding{Subtest: "too_small"}
	case bits%8 != 0:
		return &Finding{Subtest: "not_multiple_of_8"}
	case bits != 2048 && bits != 3072 && bits != 4096:
		return &Finding{Subtest: "unusual_keysize"}
	}
	if e.Cmp(big.NewInt(3)) == 0 {
		return &Finding{Subtest: "exponent_3"}
	}
	if e.Cmp(big.NewInt(65537)) != 0 {
		return &Finding{Subtest: "exponent_not_65537"}
	}
	return nil
}
